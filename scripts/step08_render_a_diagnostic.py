"""
step08_render_a_diagnostic.py — render-distribution diagnostic.

Runs `step08_render.render(...)` over a small set of test queries
against the synthetic + (optionally) real snapshot, records the
per-render token distribution (skeleton / expansion / tooltips),
and emits:

  - figures/step08_a_render_distribution.{png,pdf}   (per-snapshot)
  - tables/step08_a_render_distribution.{csv,tex}     (per-snapshot)
  - evaluation/reports/<run_id>/report.md            (per run)

Plan verification (PLAN.md step 08):
  render ≥ 16 queries across all 8 task families (2/family smoke);
  step08_render_a_diagnostic.py produces the render-distribution
  figure.
"""
from __future__ import annotations

import argparse
import csv
import datetime as _dt
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from step08_render import render, _estimate_tokens, _write_render_report, REPORT_DIR

# Determinism per the plan.
np.random.seed(17)

FIG_DIR = Path("figures")
TBL_DIR = Path("tables")
DEFAULT_RUN_ID_FMT = "render_diag_{ts}"


# Eight task families (one query per family, 2 = 16; we use 1 for smoke
# but the data structure supports more).
TASK_FAMILIES = {
    "localization": [
        "What is the anatomical localization of term X?",
    ],
    "hierarchy": [
        "List the parents of term X.",
    ],
    "sibling-discrimination": [
        "Compare term X with its sibling term Y.",
    ],
    "relation-completion": [
        "Which relations are missing for term X?",
    ],
    "multi-hop": [
        "Find a 2-hop path from X to Y.",
    ],
    "cross-ontology": [
        "Map term X in CL to its equivalent in UBERON.",
    ],
    "version-change": [
        "What changed in term X between version 1 and version 2?",
    ],
    "insufficient-information": [
        "Is term X supported by the ontology?",
    ],
}


def _now_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")


def _diagnose(
    snapshot_id: str, ontology: str, run_id: str, budgets: list[int],
) -> list[dict]:
    """Render one query per family at each budget, log every render."""
    rows: list[dict] = []
    for family, queries in TASK_FAMILIES.items():
        for q in queries:
            for budget in budgets:
                rc = render(q, snapshot_id, ontology, budget)
                out = _write_render_report(rc, run_id)
                skel_text = rc["text"].split("\n\n== EXPANDED CAPSULES ==")[0]
                if "\n\n== EXPANDED CAPSULES ==" in rc["text"]:
                    exp_text = rc["text"].split("\n\n== EXPANDED CAPSULES ==")[1]
                else:
                    exp_text = ""
                skel_tokens = _estimate_tokens(skel_text)
                exp_tokens = _estimate_tokens(exp_text)
                rows.append({
                    "family": family, "query": q, "budget": budget,
                    "skel_tokens": skel_tokens, "exp_tokens": exp_tokens,
                    "tool_tokens": rc["tokens_used"] - skel_tokens - exp_tokens,
                    "tokens_used": rc["tokens_used"],
                    "n_modules": len(rc["selected_modules"]),
                    "n_capsules": len(rc["selected_capsules"]),
                    "n_tool_calls": len(rc["exact_tool_calls"]),
                    "render_path": str(out),
                })
    return rows


def _write_csv_tex(rows: list[dict], basename: str) -> None:
    TBL_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = TBL_DIR / f"{basename}.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["family", "query", "budget", "skel_tokens", "exp_tokens",
                    "tool_tokens", "tokens_used", "n_modules", "n_capsules",
                    "n_tool_calls"])
        for r in rows:
            w.writerow([r["family"], r["query"][:60], r["budget"],
                        r["skel_tokens"], r["exp_tokens"],
                        r["tool_tokens"], r["tokens_used"],
                        r["n_modules"], r["n_capsules"], r["n_tool_calls"]])
    tex_path = TBL_DIR / f"{basename}.tex"
    with tex_path.open("w", encoding="utf-8") as fh:
        fh.write("% Auto-generated by step08_render_a_diagnostic.py\n")
        fh.write("\\begin{tabular}{lrrrrrr}\n\\toprule\n")
        fh.write("family & budget & skel & exp & tools & total \\\\\n\\midrule\n")
        for r in rows:
            fh.write(f"{r['family']} & {r['budget']} & {r['skel_tokens']} & "
                     f"{r['exp_tokens']} & {r['tool_tokens']} & {r['tokens_used']} \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")


def _plot(rows: list[dict], basename: str) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    families = sorted({r["family"] for r in rows})
    budgets = sorted({r["budget"] for r in rows})
    fig, ax = plt.subplots(1, 1, figsize=(9, 5))
    width = 0.8 / max(1, len(budgets))
    for i, b in enumerate(budgets):
        means = []
        for f in families:
            s = [r for r in rows if r["family"] == f and r["budget"] == b]
            means.append(sum(x["tokens_used"] for x in s) / max(1, len(s)))
        x = [j + i * width for j in range(len(families))]
        ax.bar(x, means, width=width, label=f"budget={b}")
    ax.set_xticks([j + 0.4 - 0.4 for j in range(len(families))])
    ax.set_xticklabels(families, rotation=30, ha="right")
    ax.set_ylabel("mean tokens used")
    ax.set_title(f"Step 08a — render distribution by family/budget")
    ax.legend()
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_DIR / f"{basename}.png", dpi=200, bbox_inches="tight")
    fig.savefig(FIG_DIR / f"{basename}.pdf", bbox_inches="tight")
    plt.close(fig)


def _write_report_md(rows: list[dict], run_id: str, snapshot_id: str) -> Path:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    out = REPORT_DIR / run_id / "report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        f"# Render-distribution report — {snapshot_id}",
        "",
        f"Run id: `{run_id}`",
        f"Generated at: {_now_iso()}",
        "",
        f"Total renders: {len(rows)}",
        f"Distinct task families: {len({r['family'] for r in rows})}",
        f"Distinct budgets: {len({r['budget'] for r in rows})}",
        "",
        "## Mean tokens used by family × budget",
        "",
        "| family |",
        "|---|",
    ]
    # family-by-budget table
    families = sorted({r["family"] for r in rows})
    budgets = sorted({r["budget"] for r in rows})
    head = "| family | " + " | ".join(f"b={b}" for b in budgets) + " |"
    sep = "|---|" + "|".join("---" for _ in budgets) + "|"
    lines = [f"# Render-distribution report — {snapshot_id}", "",
             f"Run id: `{run_id}`", f"Generated at: {_now_iso()}", "",
             f"Total renders: {len(rows)}",
             f"Distinct task families: {len(families)}",
             f"Distinct budgets: {len(budgets)}",
             "", head, sep]
    for f in families:
        cells = []
        for b in budgets:
            s = [r for r in rows if r["family"] == f and r["budget"] == b]
            if not s:
                cells.append("—")
            else:
                cells.append(f"{sum(x['tokens_used'] for x in s) / len(s):.1f}")
        lines.append(f"| {f} | " + " | ".join(cells) + " |")
    lines.append("")
    lines.append("## Per-render log")
    lines.append("")
    lines.append("| family | budget | skel | exp | tools | total |")
    lines.append("|---|---|---|---|---|---|")
    for r in rows:
        lines.append(f"| {r['family']} | {r['budget']} | {r['skel_tokens']} | "
                     f"{r['exp_tokens']} | {r['tool_tokens']} | {r['tokens_used']} |")
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def _parse_args(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--synthetic", type=str, default=None)
    p.add_argument("--snapshot", type=str, default=None)
    p.add_argument("--budgets", type=int, nargs="+", default=[256, 512, 1024])
    p.add_argument("--run-id", type=str, default=None)
    return p.parse_args(argv)


def _infer_ontology(snapshot_id: str) -> str:
    proc = Path("data/processed") / snapshot_id
    mf = proc / "manifest_processed.yaml"
    if mf.exists():
        try:
            import yaml
            return yaml.safe_load(mf.read_text())["ontology"]
        except Exception:
            pass
    return snapshot_id.split("_")[0].upper()


def main(argv=None):
    args = _parse_args(argv if argv is not None else sys.argv[1:])
    if args.synthetic:
        snapshot = args.synthetic
    elif args.snapshot:
        snapshot = args.snapshot
    else:
        print("ERROR: pass --synthetic or --snapshot", file=sys.stderr)
        return 2
    ontology = _infer_ontology(snapshot)
    run_id = args.run_id or DEFAULT_RUN_ID_FMT.format(
        ts=_now_iso().replace(":", "").replace("-", "")
    )
    rows = _diagnose(snapshot, ontology, run_id, args.budgets)
    basename = f"step08_a_render_distribution_{snapshot}"
    _write_csv_tex(rows, basename)
    _plot(rows, basename)
    out_report = _write_report_md(rows, run_id, snapshot)
    print(f"✅ {snapshot}: {len(rows)} renders, "
          f"figures/{basename}.{{png,pdf}} + tables/{basename}.csv + report {out_report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
