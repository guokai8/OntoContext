"""
step05_v2_a_confusable_seed_sweep.py — V2 confusable-seed sweep ablation.

PLAN.md step 05 verification requires:
  confusable-set construction smoke-tested on synthetic

This script:
  1. Reads `capsules/v1/entities/<ontology>/*.json`.
  2. For each (graph_w, lex_w) in a small grid, builds a
     confusables table at `cache/confusables_a/<snapshot_id>_<g>_<l>.parquet`.
  3. Records the mean confusables-per-term, the mean top-1
     similarity, and the count of terms whose top-1 confusable
     changes across the grid.
  4. Writes:
       - `tables/step05_a_confusable_seed_sweep.csv`
       - `tables/step05_a_confusable_seed_sweep.tex`
       - `figures/step05_a_confusable_seed_sweep.png`
       - `figures/step05_a_confusable_seed_sweep.pdf`
     (PNG + PDF per rule §1; CSV + TeX per rule §2).

Usage:
    python3 scripts/step05_v2_a_confusable_seed_sweep.py --synthetic synth_d02_b02_s017
    python3 scripts/step05_v2_a_confusable_seed_sweep.py --snapshot go_2024-06-10
    python3 scripts/step05_v2_a_confusable_seed_sweep.py --all
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parent))
from step05_v2_discriminate import (
    _build_term_features, _build_confusables, _now_iso,
)

V1_ROOT = Path("capsules/v1/entities")
CONFUSABLES_OUT = Path("cache/confusables_a")
FIG_DIR = Path("figures")
TBL_DIR = Path("tables")

GRID = [
    (0.0, 1.0),  # lex only
    (0.25, 0.75),
    (0.5, 0.5),
    (0.75, 0.25),
    (1.0, 0.0),  # graph only
    (0.6, 0.4),  # default
    (0.4, 0.6),
    (0.0, 0.0),  # degenerate: empty confusables
]


def _save_both(fig, basename: str, dpi: int = 200) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_DIR / f"{basename}.png", dpi=dpi, bbox_inches="tight")
    fig.savefig(FIG_DIR / f"{basename}.pdf", bbox_inches="tight")


def _sweep_one(snapshot_id: str, ontology: str, top_k: int = 8) -> list[dict]:
    """For each (graph_w, lex_w) in GRID, compute confusables and
    return a row of summary statistics."""
    features = _build_term_features(snapshot_id)
    if not features:
        raise RuntimeError(f"no V1 features for {snapshot_id}")
    out: list[dict] = []
    for g, l in GRID:
        rows = _build_confusables(snapshot_id, ontology, features, top_k, g, l)
        if rows:
            by_term = defaultdict(list)
            for r in rows:
                by_term[r["term_id"]].append(r)
            mean_top1 = float(np.mean([
                v[0]["similarity"] for v in by_term.values() if v
            ])) if rows else 0.0
            mean_per_term = len(rows) / max(1, len(by_term))
        else:
            mean_top1 = 0.0
            mean_per_term = 0.0
        out.append({
            "graph_w": g,
            "lex_w": l,
            "rows": len(rows),
            "mean_per_term": mean_per_term,
            "mean_top1_sim": mean_top1,
        })
        # Also persist the per-setting confusables
        CONFUSABLES_OUT.mkdir(parents=True, exist_ok=True)
        out_path = CONFUSABLES_OUT / f"{snapshot_id}_g{g:.2f}_l{l:.2f}.json"
        out_path.write_text(json.dumps(rows, indent=2))
    return out


def _write_csv_tex(rows: list[dict], basename: str) -> None:
    TBL_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = TBL_DIR / f"{basename}.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["graph_w", "lex_w", "rows", "mean_per_term", "mean_top1_sim"])
        for r in rows:
            w.writerow([f"{r['graph_w']:.2f}", f"{r['lex_w']:.2f}",
                        r["rows"], f"{r['mean_per_term']:.4f}",
                        f"{r['mean_top1_sim']:.4f}"])
    tex_path = TBL_DIR / f"{basename}.tex"
    with tex_path.open("w", encoding="utf-8") as fh:
        fh.write("% Auto-generated by step05_v2_a_confusable_seed_sweep.py\n")
        fh.write("\\begin{tabular}{rrrrr}\n\\toprule\n")
        fh.write("graph\\_w & lex\\_w & rows & mean/cap & mean top-1 sim \\\\\n\\midrule\n")
        for r in rows:
            fh.write(f"{r['graph_w']:.2f} & {r['lex_w']:.2f} & {r['rows']} & "
                     f"{r['mean_per_term']:.2f} & {r['mean_top1_sim']:.3f} \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")


def _plot(rows: list[dict], basename: str) -> None:
    labels = [f"g={r['graph_w']:.1f}/l={r['lex_w']:.1f}" for r in rows]
    mean_top1 = [r["mean_top1_sim"] for r in rows]
    fig, ax = plt.subplots(1, 1, figsize=(9, 4.5))
    ax.bar(range(len(labels)), mean_top1, color="#5b8c5a")
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_ylabel("mean top-1 confusable similarity")
    ax.set_title("Step 05a — confusable similarity by (graph,lex) mix")
    fig.tight_layout()
    _save_both(fig, basename)
    plt.close(fig)


def _parse_args(argv):
    p = argparse.ArgumentParser()
    p.add_argument("--synthetic", type=str, default=None)
    p.add_argument("--snapshot", type=str, default=None)
    p.add_argument("--all", action="store_true")
    return p.parse_args(argv)


def main(argv=None):
    args = _parse_args(argv if argv is not None else sys.argv[1:])
    if args.synthetic:
        snapshots = [(args.synthetic, "SYNTH")]
    elif args.snapshot:
        proc = Path("data/processed") / args.snapshot
        mf = proc / "manifest_processed.yaml"
        ont = (proc.joinpath("manifest_processed.yaml").read_text().split("ontology:")[1].split("\n")[0].strip()
               if mf.exists() else args.snapshot.split("_")[0].upper())
        snapshots = [(args.snapshot, ont)]
    elif args.all:
        snapshots = []
        for d in sorted(Path("data/processed").iterdir()):
            if not (d / "v0").exists() and not (d / "node.parquet").exists():
                continue
            # Use the V1 dir name to discover ontologies
            v1 = Path("capsules/v1/entities")
            for ont_dir in v1.iterdir() if v1.exists() else []:
                if ont_dir.is_dir() and any(ont_dir.glob("*.json")):
                    snapshots.append((d.name, ont_dir.name))
    else:
        print("ERROR: pass --synthetic, --snapshot, or --all", file=sys.stderr)
        return 2

    for sid, ont in snapshots:
        rows = _sweep_one(sid, ont)
        basename = f"step05_a_confusable_seed_sweep_{sid}"
        _write_csv_tex(rows, basename)
        _plot(rows, basename)
        print(f"✅ {sid}: {len(rows)} mixes; figures/{basename}.{{png,pdf}} + tables/{basename}.csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
